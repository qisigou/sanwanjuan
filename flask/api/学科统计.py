# 按长度倒序，保证最长前缀优先命中（如 TP3 先于 TP、B84 先于 B8）
对照前缀列表 = sorted(中图法专业对照, key=len, reverse=True)


def 读取_学科目录():
    """从目录表读取门类与二级专业，返回 (门类列表, 专业字典)"""
    with closing(类_图书检索.获取_数据库连接()) as 连接:
        行列表 = 连接.execute(
            "SELECT 编号, TRIM(名称), COALESCE(备注, '') FROM 研究生教育学科专业目录_2022 "
            "WHERE length(编号) IN (2, 4) ORDER BY 编号"
        ).fetchall()

    门类列表 = []
    门类索引 = {}
    专业字典 = {}
    for 编号, 名称, 备注 in 行列表:
        编号 = (编号 or '').strip()
        if len(编号) == 2:
            节点 = {'编号': 编号, '名称': 名称, '备注': 备注, '数量': 0, '专业': []}
            门类列表.append(节点)
            门类索引[编号] = 节点
        elif len(编号) == 4 and 编号[:2] in 门类索引:
            条目 = {'编号': 编号, '名称': 名称, '备注': 备注, '数量': 0}
            门类索引[编号[:2]]['专业'].append(条目)
            专业字典[编号] = 条目

    return 门类列表, 专业字典


def 匹配_专业编号(中图法):
    """把图书的中图法取值解析为二级专业编号，无法匹配时返回 None"""
    首段 = (中图法 or '').strip().split(',')[0].strip()
    if not 首段:
        return None
    for 前缀 in 对照前缀列表:
        if 首段.startswith(前缀):
            return 中图法专业对照[前缀]
    return None


def 构建_学科统计():
    """按门类 / 二级专业汇总藏书数量"""
    门类列表, 专业字典 = 读取_学科目录()

    with closing(类_图书检索.获取_数据库连接()) as 连接:
        行列表 = 连接.execute(
            "SELECT 中图法, COUNT(*) FROM 书籍 WHERE 存储状态 = '正常' "
            "AND 中图法 IS NOT NULL AND TRIM(中图法) != '' GROUP BY 中图法"
        ).fetchall()

    总数 = 0
    未归类 = 0
    for 中图法, 数量 in 行列表:
        总数 += 数量
        专业编号 = 匹配_专业编号(中图法)
        if 专业编号 and 专业编号 in 专业字典:
            专业字典[专业编号]['数量'] += 数量
        else:
            未归类 += 数量

    for 门类 in 门类列表:
        门类['数量'] = sum(条目['数量'] for 条目 in 门类['专业'])

    return {
        '成功': True,
        '总数': 总数,
        '已归类': 总数 - 未归类,
        '未归类': 未归类,
        '门类': 门类列表,
    }


@api_bp.route('/subject-stats')
def 学科统计():
    """返回学科门类 / 二级专业两级统计结果"""
    try:
        return jsonify(构建_学科统计())
    except Exception as e:
        return jsonify({'成功': False, 'error': str(e)}), 500
